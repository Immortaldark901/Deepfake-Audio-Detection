        "    padded = F.pad(spec, (half, half), mode='replicate')",
        "    delta = torch.zeros_like(spec)",
        "    for i in range(1, half + 1):",
        "        delta += i * (padded[:, :, half + i : half + i + n_frames] - padded[:, :, half - i : half - i + n_frames])",

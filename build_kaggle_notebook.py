        "                          window=self.window, return_complex=True, center=True, pad_mode='reflect')",
        "        mag = torch.abs(stft)",
        "        fbank_energy = torch.matmul(self.linear_fbank, mag)",
        "        log_fbank = torch.log(torch.clamp(fbank_energy, min=1e-8))",
